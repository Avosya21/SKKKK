"""Разбор вопроса чата перед поиском: возражение пользователя и расширение запроса близкими словами.

Урок 16.10 (пр. 28): на «почему ты не сказал, что обещали оценку склада?» чат согласился без проверки, а на вопрос
о складском контуре не нашёл ближайшее место — монолог заказчика про ТСД, штрихкоды и отслеживание заказа.
Возражение распознаётся по словам, утверждение из него ищется отдельно; к запросу добавляются слова, которыми
о том же говорят на созвонах (``SYNONYM_GROUPS``) — без вызова модели.
"""

from __future__ import annotations

import re

_PUSHBACK_RE = re.compile(
    r"(?<!\w)(?:"
    r"почему\s+(?:ты\s+|вы\s+)?не\s+(?:сказал|упомянул|написал|ответил|назвал|указал|учел|учёл)\w*"
    r"|(?:ты|вы)\s+(?:ошиб|забыл|пропустил|упустил|не\s+прав|неправ|перепутал)\w*"
    r"|разве\s+не|но\s+ведь|а\s+как\s+же|это\s+не\s+так|неверно|неправильно|на\s+самом\s+деле"
    r"|так\s+получается"
    r")",
    re.IGNORECASE,
)
# Начало возражения до самого утверждения: «почему ты не сказал, что …», «разве не …», «но ведь …».
_CLAIM_PREFIX_RE = re.compile(
    r"^\s*(?:почему\s+(?:ты\s+|вы\s+)?не\s+\w+(?:\s+(?:о\s+том|про\s+то))?\s*,?\s*(?:что|как)?"
    r"|(?:ты|вы)\s+(?:забыл|пропустил|упустил)\w*\s*,?\s*(?:что|про|о)?"
    r"|разве\s+не|но\s+ведь|а\s+как\s+же|так\s+получается\s*,?\s*(?:что)?)\s*",
    re.IGNORECASE,
)

# (основы слов в вопросе, слова в запрос): как о предмете говорят на созвонах и в переписке.
SYNONYM_GROUPS: tuple[tuple[tuple[str, ...], tuple[str, ...]], ...] = (
    (("склад", "тсд", "штрих", "остатк", "инвентар"),
     ("склад", "ТСД", "сканеры", "штрихкодирование", "поступление", "реализация", "остатки", "резерв", "приемка")),
    (("статус", "отслеж", "сквозн"),
     ("статусы", "отслеживать", "стадия", "отгрузка", "оплата", "логистика", "изменения", "заказ")),
    (("оценк", "стоимост", "цен", "смет", "бюджет", "сколько стоит"),
     ("оценка", "стоимость", "цена", "смета", "бюджет", "тысяч", "млн", "рублей", "часов")),
    (("срок", "дедлайн", "когда", "график"),
     ("сроки", "месяц", "недели", "дедлайн", "график", "старт", "понедельник")),
    (("аудит", "анализ", "аналитик", "обследов", "предпроект"),
     ("аудит", "аналитика", "анализ", "предпроектная", "обследование", "этап")),
    (("обещ", "договор", "обязал", "взял"),
     ("обещали", "договорились", "сделаем", "пришлем", "подготовим", "отправим", "до понедельника")),
    (("конфигурат", "комплектац", "совместим"),
     ("конфигуратор", "комплектация", "совместимость", "узлы", "опции")),
)


def is_pushback(question: str) -> bool:
    """Пользователь оспаривает прошлый ответ или утверждает факт о проекте («почему ты не сказал, что…»)."""
    return bool(_PUSHBACK_RE.search(question or ""))


def claim_of(question: str) -> str:
    """Утверждение из возражения без вводных слов — его и ищем; без вводных — весь вопрос."""
    text = (question or "").strip()
    claim, found = _CLAIM_PREFIX_RE.subn("", text, count=1)
    claim = claim.strip(" ,?!.")
    return claim if found and len(claim.split()) >= 2 else text


def expand_query(question: str) -> list[str]:
    """Слова для поиска, которых нет в вопросе, по группам ``SYNONYM_GROUPS``, сработавшим на вопрос."""
    q = (question or "").lower().replace("ё", "е")
    words = set(re.findall(r"\w+", q))
    extra: list[str] = []
    for stems, add in SYNONYM_GROUPS:
        if not any(stem in q for stem in stems):
            continue
        for word in add:
            if word.lower() not in words and word not in extra:
                extra.append(word)
    return extra
